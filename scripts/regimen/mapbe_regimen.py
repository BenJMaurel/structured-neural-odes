#!/usr/bin/env python3
"""ORACLE MAP-BE on Baaz et al.'s regimen test: the true structural model (their 1-cpt, first-order absorption, central amount starting at v,
concentration = central amount), their TRUE population parameters (log-normal ka, ke, v: means 0.4 / 0.6 / 50, sd 0.5,
their correlation matrix) and their true additive noise (sd 10; the 1e-4 proportional part is ignored). Each test patient
is fitted by MAP on the SAME samples its encoder sees (training regimen, dense or sparse), then predicted under every
regimen with their own simulator; scored exactly like dh_regimen*.py. This is the best population PK can do here (right
model, right priors) -- a realistic MAP-BE with population parameters estimated from the training patients can only be
equal or worse. The likelihood uses the CLOSED FORM of their simulator's explicit-Euler update (dt 0.01): with
a = 1 - ke dt, g = 1 - ka dt and a dose D added at step k, the recorded central amount at step n >= k gains
D ka (a^(n-k) - g^(n-k)) / (ka - ke), and the initial amount v becomes v a^n -- identical to gen_regimens.simulate
(checked at start). Same patients as the EB-VAE runs (data regenerated by dh_regimen_v2.py's code via runpy).
    mapbe_regimen.py <n_per_arm> <dense|sparse> <seed> <out.json> [firstint]
firstint: the iScience format -- for EACH regimen, MAP on the samples of that regimen's first dosing interval
(observed with the same stream seed + 4242 as the learned models), predict the same regimen, score AUC on [t2, 30 h]."""
import os as _os; REPO = _os.path.abspath(_os.path.join(_os.path.dirname(_os.path.abspath(__file__)), '../..'))
import os, sys, json, runpy, time
import numpy as np, torch
os.chdir(REPO); sys.path.insert(0, os.getcwd())
NA, DESIGN, SEED, OUT = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4]
FIRSTINT = len(sys.argv) > 5 and sys.argv[5] == 'firstint'
t0 = time.time()
sys.argv = ['x', NA, DESIGN, SEED, '/tmp/unused.json', '--no-check'] + (['--protocol', 'firstint'] if FIRSTINT else [])
g = runpy.run_path('scripts/regimen/dh_regimen_v2.py', run_name='mapbe')      # data only (no training happens)
G, regs, truth, t_eval, EG, SAMP = g['G'], g['regs'], g['truth'], g['t_eval'], g['EG'], g['SAMP']
y_te, A_te, P_te = g['y_te'], g['A_te'], g['P_te']
torch.set_default_dtype(torch.float64)
DT = G.DT
mu = torch.tensor(np.log([G.KA, G.KE, G.V]))
Om = torch.tensor(np.outer([G.SD] * 3, [G.SD] * 3) * G.CORR); Om_inv = torch.linalg.inv(Om)
SIG = float(G.ADD_E)
obs_idx = np.array([int(np.argmin(np.abs(t_eval - s))) for s in SAMP])


def dose_steps(times):
    return [int(np.argmax(t_eval >= t)) for t in times]       # first step with t >= dose time (their loop)


def conc_at(eta, times, amounts, idx):
    """central amount at grid indices idx, eta [B,3] = log(ka, ke, v), amounts [B,K]"""
    ka, ke, v = torch.exp(eta).unbind(-1)
    ke = torch.where((ka - ke).abs() < 1e-7, ke + 1e-7, ke)
    a, gg = 1 - ke * DT, 1 - ka * DT
    n = torch.tensor(idx, dtype=torch.float64)
    c = v[:, None] * a[:, None] ** n[None, :]
    for kd, k in enumerate(dose_steps(times)):
        m = (n - k).clamp(min=0)[None, :]
        c = c + (n[None, :] >= k) * torch.tensor(amounts[:, kd])[:, None] * ka[:, None] * (a[:, None] ** m - gg[:, None] ** m) / (ka - ke)[:, None]
    return c


def conc_at_mm(eta, times, amounts, idx):
    """saturable simulator (REGIMEN_KM): their explicit Euler loop (dt 0.01, clipping at 0) in torch, central amount at idx"""
    ka, ke, v = torch.exp(eta).unbind(-1); Vm = ke * G.KM
    gut = torch.zeros_like(v); cen = v.clone(); A = torch.tensor(amounts); steps = dose_steps(times); out = {}
    want = set(int(i) for i in idx); n_end = int(max(idx))
    for n in range(n_end + 1):
        for kd, k in enumerate(steps):
            if k == n:
                gut = gut + A[:, kd]
        if n in want:
            out[n] = cen
        gut, cen = (gut - ka * gut * DT).clamp(min=0), (cen + (ka * gut - Vm * cen / (G.KM + cen)) * DT).clamp(min=0)
    return torch.stack([out[int(i)] for i in idx], 1)


CONC = conc_at if G.KM is None else conc_at_mm
if G.KM is not None:
    print(f'SATURABLE simulator (Km {G.KM:g}): MAP-BE with the true saturable model (numeric Euler, dt {DT})', flush=True)

# exactness check against their simulator (true parameters, training regimen)
times0, A0 = regs['train']
c_cf = CONC(torch.tensor(np.log(P_te[:20])), times0, A0[:20], np.arange(len(t_eval))).numpy()
_, c_sim = G.simulate(P_te[:20], times0, A0[:20])
rel = np.abs(c_cf - c_sim).max() / np.abs(c_sim).max()
print(f'closed form vs their simulator: max |diff| / max conc = {rel:.2e}', flush=True)
assert rel < 1e-9, 'closed form does not reproduce the simulator'

def fit_map(Y, times, A, idx):
    """MAP of log(ka, ke, v) per patient on the samples at grid indices idx (one joint L-BFGS, patients independent)"""
    Y = torch.tensor(Y); eta = mu.repeat(len(Y), 1).clone().requires_grad_(True)
    opt = torch.optim.LBFGS([eta], lr=1, max_iter=500, tolerance_grad=1e-10, tolerance_change=1e-12, line_search_fn='strong_wolfe')
    def objective():
        opt.zero_grad(); c = CONC(eta, times, A, idx); d = eta - mu
        f = ((Y - c) ** 2).sum() / (2 * SIG ** 2) + 0.5 * torch.einsum('bi,ij,bj->', d, Om_inv, d); f.backward(); return f
    for _ in range(5):
        opt.step(objective)
    return torch.exp(eta.detach()).numpy(), float(eta.grad.abs().max())


if FIRSTINT:
    res = dict(model='MAP-BE oracle, iScience format (first dosing interval of each regimen observed)', protocol='firstint',
               N_per_arm=int(NA), design=DESIGN, seed=int(SEED), n_samples_per_patient=len(SAMP), individual={}, window_start={})
    for name in G.REGIMENS:
        times, A = regs[name]; cut = float(sorted(times)[1]); m = SAMP < cut
        th, gn = fit_map(g['y_obs'][name][:, m], times, A, obs_idx[m])
        _, c_hat = G.simulate(th, times, A); w = EG >= cut - 1e-9
        pred = np.stack([np.interp(EG, t_eval, c) for c in c_hat])[:, w]; tru = np.stack([np.interp(EG, t_eval, c) for c in truth[name]])[:, w]
        r = np.trapezoid(pred, EG[w], axis=1) / np.trapezoid(tru, EG[w], axis=1) - 1; nrmse = np.sqrt(np.mean((pred - tru) ** 2, 1)) / np.mean(tru, 1)
        res['individual'][name] = dict(auc_abs_median=100 * float(np.median(np.abs(r))), nrmse_median=100 * float(np.median(nrmse)),
                                       auc_bias_median=100 * float(np.median(r)), auc_err_per_patient=[float(x) for x in r], max_abs_grad=gn)
        res['window_start'][name] = cut
        print(f'{name:8s} first {cut:g} h ({int(m.sum())} samples) -> |AUC({cut:g}-30 h) err| {res["individual"][name]["auc_abs_median"]:5.2f}%  '
              f'bias {res["individual"][name]["auc_bias_median"]:+5.2f}%  (max |grad| {gn:.1e})', flush=True)
    os.makedirs(os.path.dirname(os.path.abspath(OUT)), exist_ok=True); json.dump(res, open(OUT, 'w'), indent=1)
    print(f'MAPBE_DONE {(time.time() - t0) / 60:.1f} min', flush=True); sys.exit(0)

# MAP per patient (independent; one joint L-BFGS on the summed objective)
Y = torch.tensor(y_te)
eta = mu.repeat(len(Y), 1).clone().requires_grad_(True)
opt = torch.optim.LBFGS([eta], lr=1, max_iter=500, tolerance_grad=1e-10, tolerance_change=1e-12, line_search_fn='strong_wolfe')


def objective():
    opt.zero_grad()
    c = CONC(eta, times0, A_te, obs_idx)
    d = eta - mu
    f = ((Y - c) ** 2).sum() / (2 * SIG ** 2) + 0.5 * torch.einsum('bi,ij,bj->', d, Om_inv, d)
    f.backward()
    return f


for _ in range(5):
    opt.step(objective)
gnorm = float(eta.grad.abs().max())
theta = torch.exp(eta.detach()).numpy()
print(f'MAP done: max |gradient| {gnorm:.2e}; EBE vs true log-param RMS error (ka, ke, v): '
      f'{np.sqrt(np.mean((np.log(theta) - np.log(P_te)) ** 2, 0)).round(3).tolist()}', flush=True)

res = dict(model='MAP-BE oracle (true model, true population parameters, true noise)', N_per_arm=int(NA), design=DESIGN,
           seed=int(SEED), n_samples_per_patient=len(SAMP), max_abs_grad=gnorm, individual={})
for name in G.REGIMENS:
    times, A = regs[name]
    _, c_hat = G.simulate(theta, times, A)
    pred = np.stack([np.interp(EG, t_eval, c) for c in c_hat])
    tru = np.stack([np.interp(EG, t_eval, c) for c in truth[name]])
    r = np.trapezoid(pred, EG, axis=1) / np.trapezoid(tru, EG, axis=1) - 1
    nrmse = np.sqrt(np.mean((pred - tru) ** 2, 1)) / np.mean(tru, 1)
    res['individual'][name] = dict(auc_abs_median=100 * float(np.median(np.abs(r))), nrmse_median=100 * float(np.median(nrmse)),
                                   auc_bias_median=100 * float(np.median(r)), auc_err_per_patient=[float(x) for x in r])
    print(f'{name:8s} individual |AUC err| {res["individual"][name]["auc_abs_median"]:5.2f}%  nRMSE '
          f'{res["individual"][name]["nrmse_median"]:5.2f}%  bias {res["individual"][name]["auc_bias_median"]:+5.2f}%', flush=True)
os.makedirs(os.path.dirname(os.path.abspath(OUT)), exist_ok=True)
json.dump(res, open(OUT, 'w'), indent=1)
print(f'MAPBE_DONE {(time.time() - t0) / 60:.1f} min', flush=True)
